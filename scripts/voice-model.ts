/**
 * Voice input setup. Two jobs:
 *
 *  1. Download the Vosk small English model (Apache-2.0, alphacephei.com/vosk/models) as the gzipped tar
 *     vosk-browser expects, to public/vosk/model.tar.gz. Vite copies public/ into dist/, so `npm run pack`
 *     ships it inside the .ehpk. The file is ~41 MB and is not committed (see .gitignore).
 *  2. Build src/words/spoken.ts: the allowlist words the model can recognise. The recogniser is restricted to
 *     that list (a Vosk grammar), and a grammar word outside the model vocabulary is dropped with a warning,
 *     so the list must be filtered. This file is committed; it only changes when the word lists or model do.
 *
 *   npm run voice-model            # download if missing, then build spoken.ts
 *   npm run voice-model -- --force # download again
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gunzipSync } from 'node:zlib'
import { isValidGuess } from '../src/words'
import { ALLOWLIST_PACKED } from '../src/words/allowlist'
import { SPELL_TOKENS } from '../src/voice/spell'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const MODEL_URL = 'https://ccoreilly.github.io/vosk-browser/models/vosk-model-small-en-us-0.15.tar.gz'
const MODEL_FILE = join(root, 'public/vosk/model.tar.gz')

async function download(): Promise<void> {
  if (existsSync(MODEL_FILE) && !process.argv.includes('--force')) {
    console.log(`model present: ${MODEL_FILE}`)
    return
  }
  console.log(`downloading ${MODEL_URL}`)
  const res = await fetch(MODEL_URL)
  if (!res.ok) throw new Error(`download failed: ${res.status} ${res.statusText}`)
  const bytes = new Uint8Array(await res.arrayBuffer())
  mkdirSync(dirname(MODEL_FILE), { recursive: true })
  writeFileSync(MODEL_FILE, bytes)
  console.log(`saved ${(bytes.length / 1e6).toFixed(1)} MB`)
}

/** Minimal ustar reader: the contents of the first entry whose path ends with `suffix`. */
function tarEntry(tar: Uint8Array, suffix: string): Uint8Array {
  const text = (a: number, b: number) => new TextDecoder().decode(tar.subarray(a, b)).replace(/\0.*$/s, '')
  for (let p = 0; p + 512 <= tar.length; ) {
    const name = text(p, p + 100)
    if (!name) break
    const prefix = text(p + 345, p + 500)
    const size = parseInt(text(p + 124, p + 136).trim() || '0', 8)
    const path = prefix ? `${prefix}/${name}` : name
    if (path.endsWith(suffix)) return tar.subarray(p + 512, p + 512 + size)
    p += 512 + Math.ceil(size / 512) * 512
  }
  throw new Error(`${suffix} not found in model archive`)
}

/**
 * The model vocabulary: the largest OpenFst symbol table inside graph/Gr.fst.
 * Layout: int32 magic, string name, int64 available key, int64 size, then size × (string, int64 key),
 * strings being int32 length + bytes, all little-endian.
 */
function vocabulary(fst: Uint8Array): Set<string> {
  const MAGIC = 2125658996
  const view = new DataView(fst.buffer, fst.byteOffset, fst.byteLength)
  const dec = new TextDecoder()
  let best: string[] = []
  for (let pos = 0; pos + 4 <= fst.length; pos++) {
    if (view.getInt32(pos, true) !== MAGIC) continue
    try {
      let p = pos + 4
      const nameLen = view.getInt32(p, true)
      if (nameLen < 0 || nameLen > 1024) continue
      p += 4 + nameLen + 8
      const size = Number(view.getBigInt64(p, true))
      p += 8
      if (size <= 0 || size > 5_000_000) continue
      const words: string[] = []
      for (let i = 0; i < size; i++) {
        const len = view.getInt32(p, true)
        if (len < 0 || len > 256) throw new Error('bad symbol')
        words.push(dec.decode(fst.subarray(p + 4, p + 4 + len)))
        p += 4 + len + 8
      }
      if (words.length > best.length) best = words
    } catch {
      // not a symbol table after all
    }
  }
  if (best.length < 1000) throw new Error('model vocabulary not found in Gr.fst')
  return new Set(best)
}

await download()
const tar = gunzipSync(readFileSync(MODEL_FILE))
const vocab = vocabulary(tarEntry(tar, 'graph/Gr.fst'))
console.log(`model vocabulary: ${vocab.size} words`)

const missingSpell = SPELL_TOKENS.filter((t) => !vocab.has(t))
if (missingSpell.length) throw new Error(`spelling words missing from the model: ${missingSpell.join(' ')}`)

const allow: string[] = []
for (let i = 0; i < ALLOWLIST_PACKED.length; i += 5) allow.push(ALLOWLIST_PACKED.slice(i, i + 5))
const spoken = allow.filter((w) => vocab.has(w) && isValidGuess(w)).sort()
console.log(`spoken words: ${spoken.length} of ${allow.length} allowed guesses`)

writeFileSync(
  join(root, 'src/words/spoken.ts'),
  [
    '// GENERATED by scripts/voice-model.ts — do not edit by hand.',
    '// Allowed guesses that the Vosk small English model (vosk-model-small-en-us-0.15) can recognise.',
    `// ${spoken.length} words.`,
    `export const SPOKEN_PACKED = '${spoken.join('')}'`,
    '',
  ].join('\n'),
)
console.log('wrote src/words/spoken.ts')
